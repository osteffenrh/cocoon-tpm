//! Pure Rust AEAD implementations, based on the RustCrypto `aes-gcm` crate.

extern crate alloc;

use aes_gcm::{Aes256Gcm, KeyInit, aead::AeadInPlace};

use crate::CryptoError;
use crate::aead::AeadAlg;
use crate::io_slices::{
    CryptoIoSlicesIter, CryptoIoSlicesMutIter, CryptoWalkableIoSlicesIter, CryptoWalkableIoSlicesMutIter,
};
use crate::utils_common::{
    alloc::try_alloc_zeroizing_vec,
    io_slices::{IoSlicesIterCommon as _, IoSlicesMutIter as _, SingletonIoSlice, SingletonIoSliceMut},
    zeroize,
};
use alloc::vec::Vec;

const GCM_IV_LEN: usize = 12;
const GCM_TAG_LEN: usize = 16;
const AES256_GCM_KEY_LEN: usize = 32;

/// An AEAD instance, i.e. an algorithm together with a key.
///
/// The instance can get used for any number of one-shot
/// [encryption](AeadInstance::encrypt_in_place) and
/// [decryption](AeadInstance::decrypt_in_place) operations, also interleaved.
///
/// The key material gets zeroized on drop if the `zeroize` Cargo feature is
/// enabled.
///
/// The RustCrypto `aes-gcm` implementation can process contiguous message
/// buffers only. Message or AAD data spread over multiple buffers gets copied
/// into a single intermediate buffer internally, which in turn gets zeroized
/// on drop (with the `zeroize` Cargo feature enabled).
pub struct AeadInstance {
    alg: AeadAlg,
    inner: Aes256Gcm,
}

/// The AAD gathered from an [*IO slice
/// iterator*](crate::utils_common::io_slices), either a borrowed reference
/// to the single input slice, or an owned copy assembled from multiple input
/// slices.
enum GatheredAad<'a> {
    Borrowed(&'a [u8]),
    Owned(zeroize::Zeroizing<Vec<u8>>),
}

impl GatheredAad<'_> {
    fn as_slice(&self) -> &[u8] {
        match self {
            Self::Borrowed(slice) => slice,
            Self::Owned(vec) => vec.as_slice(),
        }
    }
}

/// Gather the AAD supplied through an *IO slice iterator* into contiguous
/// memory, as required by the RustCrypto implementation. The common case of
/// the AAD being held in a single buffer doesn't involve any copy.
fn gather_aad<'a, AI: CryptoIoSlicesIter<'a>>(mut aad: AI) -> Result<GatheredAad<'a>, CryptoError> {
    let first = match aad.next_slice(None)? {
        Some(first) => first,
        None => return Ok(GatheredAad::Borrowed(&[])),
    };
    if aad.is_empty()? {
        return Ok(GatheredAad::Borrowed(first));
    }

    let mut gathered = Vec::with_capacity(first.len());
    gathered.extend_from_slice(first);
    while let Some(slice) = aad.next_slice(None)? {
        gathered.extend_from_slice(slice);
    }
    Ok(GatheredAad::Owned(zeroize::Zeroizing::from(gathered)))
}

/// Verify that the source and destination buffer lists are of the same total
/// length and return that length.
fn check_lengths<'b, 'c, SI: CryptoWalkableIoSlicesIter<'b>, DI: CryptoWalkableIoSlicesMutIter<'c>>(
    src: &SI,
    dst: &DI,
) -> Result<usize, CryptoError> {
    let src_len = src.total_len()?;
    let dst_len = dst.total_len()?;
    if src_len != dst_len {
        return Err(CryptoError::InvalidMessageLength);
    }
    Ok(src_len)
}

impl AeadInstance {
    /// Create a new AEAD instance for the specified algorithm and key.
    ///
    /// # Arguments:
    ///
    /// * `alg` - The AEAD algorithm.
    /// * `key` - The key, of the length required by the algorithm.
    pub fn new(alg: AeadAlg, key: &[u8]) -> Result<Self, CryptoError> {
        let key: &[u8; AES256_GCM_KEY_LEN] = key.try_into().map_err(|_| CryptoError::KeySize)?;
        let inner = match alg {
            AeadAlg::Aes256Gcm => Aes256Gcm::new(aes_gcm::Key::<Aes256Gcm>::from_slice(key)),
        };
        Ok(Self { alg, inner })
    }

    /// The IV length in bytes expected by all encryption and decryption
    /// operations.
    pub fn iv_len(&self) -> usize {
        match self.alg {
            AeadAlg::Aes256Gcm => GCM_IV_LEN,
        }
    }

    /// The authentication tag length in bytes generated by encryption and
    /// expected by decryption.
    pub fn tag_len(&self) -> usize {
        match self.alg {
            AeadAlg::Aes256Gcm => GCM_TAG_LEN,
        }
    }

    /// One-shot authenticated encryption.
    ///
    /// # Arguments:
    ///
    /// * `iv` - The IV, of length [`Self::iv_len()`].
    /// * `aad` - The additional authenticated data.
    /// * `ciphertext` - The destination buffers to write the ciphertext to.
    ///   Their total length must equal the total length of the `plaintext`
    ///   buffers. The plaintext and ciphertext buffers must not partially
    ///   overlap.
    /// * `plaintext` - The source buffers holding the message to encrypt.
    /// * `tag` - Output buffer of length [`Self::tag_len()`], receiving the
    ///   detached authentication tag.
    ///
    /// # Errors:
    ///
    /// * [`InvalidMessageLength`](CryptoError::InvalidMessageLength) - The
    ///   total lengths of the `plaintext` and `ciphertext` buffer lists
    ///   differ.
    pub fn encrypt<'a, 'b, 'c, AI, SI, DI>(
        &mut self,
        iv: &[u8],
        aad: AI,
        mut ciphertext: DI,
        mut plaintext: SI,
        tag: &mut [u8],
    ) -> Result<(), CryptoError>
    where
        AI: CryptoIoSlicesIter<'a>,
        SI: CryptoWalkableIoSlicesIter<'b>,
        DI: CryptoWalkableIoSlicesMutIter<'c>,
    {
        self.check_iv_tag(iv, tag)?;
        let msg_len = check_lengths(&plaintext, &ciphertext)?;
        let aad = gather_aad(aad)?;
        let nonce = aes_gcm::Nonce::from_slice(iv);

        let result_tag = if msg_len == 0 {
            self.inner.encrypt_in_place_detached(nonce, aad.as_slice(), &mut [])
        } else if plaintext.next_slice_len()? == msg_len && ciphertext.next_slice_len()? == msg_len {
            // Fast path: both the plaintext and the ciphertext are held in a
            // single contiguous buffer each.
            let plaintext = plaintext.next_slice(Some(msg_len))?.ok_or(CryptoError::Internal)?;
            let ciphertext = ciphertext.next_slice_mut(Some(msg_len))?.ok_or(CryptoError::Internal)?;
            ciphertext.copy_from_slice(plaintext);
            self.inner.encrypt_in_place_detached(nonce, aad.as_slice(), ciphertext)
        } else {
            // Gather the plaintext scattered over multiple buffers, encrypt
            // there and distribute the result to the ciphertext buffers.
            let mut scratch = try_alloc_zeroizing_vec(msg_len)?;
            SingletonIoSliceMut::new(scratch.as_mut_slice())
                .map_infallible_err::<CryptoError>()
                .copy_from_iter(&mut plaintext)?;
            let result = self
                .inner
                .encrypt_in_place_detached(nonce, aad.as_slice(), scratch.as_mut_slice());
            ciphertext.copy_from_iter(&mut SingletonIoSlice::new(scratch.as_slice()).map_infallible_err())?;
            result
        };
        let result_tag = result_tag.map_err(|_| CryptoError::Internal)?;
        tag.copy_from_slice(&result_tag);
        Ok(())
    }

    /// One-shot in-place authenticated encryption with detached tag.
    ///
    /// # Arguments:
    ///
    /// * `iv` - The IV, of length [`Self::iv_len()`].
    /// * `aad` - The additional authenticated data.
    /// * `buf` - The source/destination buffers holding the message to
    ///   encrypt, to be replaced by the ciphertext in place.
    /// * `tag` - Output buffer of length [`Self::tag_len()`], receiving the
    ///   authentication tag.
    pub fn encrypt_in_place<'a, 'b, AI, DI>(
        &mut self,
        iv: &[u8],
        aad: AI,
        mut buf: DI,
        tag: &mut [u8],
    ) -> Result<(), CryptoError>
    where
        AI: CryptoIoSlicesIter<'a>,
        DI: CryptoIoSlicesMutIter<'b>,
    {
        self.check_iv_tag(iv, tag)?;
        let aad = gather_aad(aad)?;
        let nonce = aes_gcm::Nonce::from_slice(iv);

        // Collect the buffer slices upfront: the message has to get processed
        // as a whole, but the result has to get written back to the buffers
        // in a second pass.
        let mut slices: Vec<&'b mut [u8]> = Vec::new();
        while let Some(slice) = buf.next_slice_mut(None)? {
            slices.push(slice);
        }

        let result_tag = if slices.is_empty() {
            self.inner.encrypt_in_place_detached(nonce, aad.as_slice(), &mut [])
        } else if slices.len() == 1 {
            // Fast path: the message is held in a single contiguous buffer.
            let slice = slices.swap_remove(0);
            self.inner.encrypt_in_place_detached(nonce, aad.as_slice(), slice)
        } else {
            let msg_len = slices.iter().map(|slice| slice.len()).sum();
            let mut scratch = try_alloc_zeroizing_vec(msg_len)?;
            let mut offset = 0;
            for slice in slices.iter() {
                scratch[offset..offset + slice.len()].copy_from_slice(slice);
                offset += slice.len();
            }
            let result = self
                .inner
                .encrypt_in_place_detached(nonce, aad.as_slice(), scratch.as_mut_slice());
            let mut offset = 0;
            for slice in slices.iter_mut() {
                slice.copy_from_slice(&scratch[offset..offset + slice.len()]);
                offset += slice.len();
            }
            result
        };
        let result_tag = result_tag.map_err(|_| CryptoError::Internal)?;
        tag.copy_from_slice(&result_tag);
        Ok(())
    }

    /// One-shot authenticated decryption.
    ///
    /// # Arguments:
    ///
    /// * `iv` - The IV, of length [`Self::iv_len()`].
    /// * `aad` - The additional authenticated data.
    /// * `plaintext` - The destination buffers to write the plaintext to.
    ///   Their total length must equal the total length of the `ciphertext`
    ///   buffers. The plaintext and ciphertext buffers must not partially
    ///   overlap.
    /// * `ciphertext` - The source buffers holding the message to decrypt.
    /// * `tag` - The detached authentication tag.
    ///
    /// # Errors:
    ///
    /// * [`InvalidMessageLength`](CryptoError::InvalidMessageLength) - The
    ///   total lengths of the `plaintext` and `ciphertext` buffer lists
    ///   differ.
    /// * [`SignatureVerificationFailure`](CryptoError::SignatureVerificationFailure)
    ///   - Authentication of the ciphertext, tag or associated data failed.
    ///     The contents of the plaintext buffers are unspecified in this
    ///     case.
    pub fn decrypt<'a, 'b, 'c, AI, SI, DI>(
        &mut self,
        iv: &[u8],
        aad: AI,
        mut plaintext: DI,
        mut ciphertext: SI,
        tag: &[u8],
    ) -> Result<(), CryptoError>
    where
        AI: CryptoIoSlicesIter<'a>,
        SI: CryptoWalkableIoSlicesIter<'b>,
        DI: CryptoWalkableIoSlicesMutIter<'c>,
    {
        self.check_iv_tag(iv, tag)?;
        let msg_len = check_lengths(&ciphertext, &plaintext)?;
        let aad = gather_aad(aad)?;
        let nonce = aes_gcm::Nonce::from_slice(iv);
        let tag = aes_gcm::Tag::from_slice(tag);

        let result = if msg_len == 0 {
            self.inner
                .decrypt_in_place_detached(nonce, aad.as_slice(), &mut [], tag)
        } else if ciphertext.next_slice_len()? == msg_len && plaintext.next_slice_len()? == msg_len {
            // Fast path: both the ciphertext and the plaintext are held in a
            // single contiguous buffer each.
            let ciphertext = ciphertext.next_slice(Some(msg_len))?.ok_or(CryptoError::Internal)?;
            let plaintext = plaintext.next_slice_mut(Some(msg_len))?.ok_or(CryptoError::Internal)?;
            plaintext.copy_from_slice(ciphertext);
            self.inner
                .decrypt_in_place_detached(nonce, aad.as_slice(), plaintext, tag)
        } else {
            // Decrypt the ciphertext scattered over multiple buffers in a
            // single intermediate buffer and distribute the result to the
            // plaintext buffers once authentication has succeeded.
            let mut scratch = try_alloc_zeroizing_vec(msg_len)?;
            SingletonIoSliceMut::new(scratch.as_mut_slice())
                .map_infallible_err::<CryptoError>()
                .copy_from_iter(&mut ciphertext)?;
            let result = self
                .inner
                .decrypt_in_place_detached(nonce, aad.as_slice(), scratch.as_mut_slice(), tag);
            if result.is_ok() {
                plaintext.copy_from_iter(&mut SingletonIoSlice::new(scratch.as_slice()).map_infallible_err())?;
            }
            result
        };
        result.map_err(|_| CryptoError::SignatureVerificationFailure)?;
        Ok(())
    }

    /// One-shot in-place authenticated decryption with detached tag.
    ///
    /// # Errors:
    ///
    /// * [`SignatureVerificationFailure`](CryptoError::SignatureVerificationFailure)
    ///   - Authentication of the ciphertext, tag or associated data failed.
    ///     The contents of the message buffers are unspecified in this case.
    ///
    /// # Arguments:
    ///
    /// * `iv` - The IV, of length [`Self::iv_len()`].
    /// * `aad` - The additional authenticated data.
    /// * `buf` - The source/destination buffers holding the ciphertext to
    ///   decrypt, to be replaced by the plaintext in place.
    /// * `tag` - The detached authentication tag.
    pub fn decrypt_in_place<'a, 'b, AI, DI>(
        &mut self,
        iv: &[u8],
        aad: AI,
        mut buf: DI,
        tag: &[u8],
    ) -> Result<(), CryptoError>
    where
        AI: CryptoIoSlicesIter<'a>,
        DI: CryptoIoSlicesMutIter<'b>,
    {
        self.check_iv_tag(iv, tag)?;
        let aad = gather_aad(aad)?;
        let nonce = aes_gcm::Nonce::from_slice(iv);
        let tag = aes_gcm::Tag::from_slice(tag);

        // Collect the buffer slices upfront: the message has to get processed
        // as a whole, but the result has to get written back to the buffers
        // in a second pass.
        let mut slices: Vec<&'b mut [u8]> = Vec::new();
        while let Some(slice) = buf.next_slice_mut(None)? {
            slices.push(slice);
        }

        let result = if slices.is_empty() {
            self.inner
                .decrypt_in_place_detached(nonce, aad.as_slice(), &mut [], tag)
        } else if slices.len() == 1 {
            // Fast path: the message is held in a single contiguous buffer.
            let slice = slices.swap_remove(0);
            self.inner.decrypt_in_place_detached(nonce, aad.as_slice(), slice, tag)
        } else {
            let msg_len = slices.iter().map(|slice| slice.len()).sum();
            let mut scratch = try_alloc_zeroizing_vec(msg_len)?;
            let mut offset = 0;
            for slice in slices.iter() {
                scratch[offset..offset + slice.len()].copy_from_slice(slice);
                offset += slice.len();
            }
            let result = self
                .inner
                .decrypt_in_place_detached(nonce, aad.as_slice(), scratch.as_mut_slice(), tag);
            if result.is_ok() {
                let mut offset = 0;
                for slice in slices.iter_mut() {
                    slice.copy_from_slice(&scratch[offset..offset + slice.len()]);
                    offset += slice.len();
                }
            }
            result
        };
        result.map_err(|_| CryptoError::SignatureVerificationFailure)?;
        Ok(())
    }

    fn check_iv_tag(&self, iv: &[u8], tag: &[u8]) -> Result<(), CryptoError> {
        if iv.len() != self.iv_len() {
            return Err(CryptoError::InvalidIV);
        }
        if tag.len() != self.tag_len() {
            return Err(CryptoError::InvalidParams);
        }
        Ok(())
    }
}
